#!/usr/bin/env node
/**
 * engine/docs/targets-doc.cjs — Renders docs/targets.md from core/templates/targets.json.
 *
 * The client table in the docs is generated, not hand-written, so it cannot
 * drift from the config the sync engine actually uses.
 *
 * Usage:
 *   node engine/docs/targets-doc.cjs          # (re)write docs/targets.md
 *   node engine/docs/targets-doc.cjs --check  # exit 1 if docs/targets.md is stale
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const TARGETS_FILE = path.join(ROOT, 'core', 'templates', 'targets.json');
const DOC_FILE = path.join(ROOT, 'docs', 'targets.md');

function render() {
  const { targets } = JSON.parse(fs.readFileSync(TARGETS_FILE, 'utf8'));
  const code = (v) => (v ? `\`${v}\`` : '-');
  const rows = targets.map((t) => [
    `**${t.name}**`,
    t.category || '-',
    code(t.rulesFile),
    code(t.traitsFile),
    code(t.hooksConfigFile),
    code(t.skillsDir),
  ].join(' | '));

  const hooked = targets.filter((t) => t.hooksConfigFile).length;
  const skilled = targets.filter((t) => t.skillsDir).length;

  return [
    '# Supported clients',
    '',
    '<!-- GENERATED by engine/docs/targets-doc.cjs from core/templates/targets.json. Do not edit by hand; run `npm run docs:targets`. -->',
    '',
    `${targets.length} targets are defined in \`core/templates/targets.json\`. \`npm run sync\` compiles \`core/rules/global-rules.md\` (plus traits and the safety policy) into each client's rules file. A dash means the client has no such surface and the harness falls back to the declarative guards in the rules file only.`,
    '',
    `- Rules file synced: **${targets.length} of ${targets.length}**`,
    `- Hook proxy wired (\`engine/hooks/dashclaw-guard.cjs\` registered in the client's hook config): **${hooked} of ${targets.length}**`,
    `- Skills directory linked (junction or export): **${skilled} of ${targets.length}**`,
    '',
    '| Client | Category | Rules file | Traits file | Hook config | Skills dir |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
    '## Adding a client',
    '',
    'Add an entry to `core/templates/targets.json` (fields: `id`, `name`, `category`, `rulesFile`, optional `traitsFile`, `hooksConfigFile`, `skillsDir`, `dialect`, `preamble`), run `npm run sync:check`, then `npm run docs:targets` and commit the regenerated table. Do not hardcode client paths anywhere else.',
    '',
  ].join('\n');
}

function main() {
  const out = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(DOC_FILE) ? fs.readFileSync(DOC_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[targets-doc] docs/targets.md is stale. Run: npm run docs:targets');
      process.exit(1);
    }
    console.log('[targets-doc] docs/targets.md is current.');
    return;
  }
  fs.mkdirSync(path.dirname(DOC_FILE), { recursive: true });
  fs.writeFileSync(DOC_FILE, out, 'utf8');
  console.log(`[targets-doc] wrote ${path.relative(ROOT, DOC_FILE)}`);
}

if (require.main === module) main();

module.exports = { render };
