#!/usr/bin/env node
/**
 * engine/docs/targets-doc.cjs — Renders docs/targets.md from core/templates/targets.json.
 *
 * The client table in the docs is generated, not hand-written, so it cannot
 * drift from the registry the port engine actually reads.
 *
 * Usage:
 *   node engine/docs/targets-doc.cjs          # (re)write docs/targets.md
 *   node engine/docs/targets-doc.cjs --check  # exit 1 if docs/targets.md is stale
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const TARGETS_FILE = path.join(ROOT, 'core', 'templates', 'targets.json');
const DOC_FILE = path.join(ROOT, 'docs', 'targets.md');

// A hook config file only means something when an adapter knows how to write
// that client's hook format. Everywhere else the guards are declarative rules.
const HOOK_ADAPTERS = new Set(['codex', 'claude', 'gemini', 'agy', 'cursor']);

const code = (v) => (v ? `\`${v}\`` : '-');
const drivesHooks = (t) => Boolean(t.hooksConfigFile && HOOK_ADAPTERS.has(t.adapter));

function render() {
  const { targets } = JSON.parse(fs.readFileSync(TARGETS_FILE, 'utf8'));

  const rows = targets.map((t) => [
    `**${t.name}**`,
    t.category || '-',
    code(t.home),
    code(t.rulesFile),
    drivesHooks(t) ? code(t.hooksConfigFile) : '-',
    code(t.skillsDir),
    code(t.agentsDir),
    code(t.commandsDir),
    code(t.mcpConfigFile),
  ].join(' | '));

  const n = targets.length;
  const count = (fn) => targets.filter(fn).length;
  const of = (label, k) => `- ${label}: **${k} of ${n}**`;

  return [
    '# Supported clients',
    '',
    '<!-- GENERATED by engine/docs/targets-doc.cjs from core/templates/targets.json. Do not edit by hand; run `npm run docs:targets`. -->',
    '',
    `${n} clients are defined in \`core/templates/targets.json\`. \`npm run port\` captures the client you actually drive (Claude Code or Codex) and renders that harness into every other client installed on the machine: rules, hooks, skills, subagents, slash commands, MCP servers and permissions. A dash means the client has no such surface, so nothing is written there and the harness falls back to the declarative guards in the rules file.`,
    '',
    of('Rules file written', n),
    of('Hooks driven (an adapter writes the client\'s own hook config)', count(drivesHooks)),
    of('Skills linked (junction or symlink, never a copy)', count((t) => t.skillsDir)),
    of('Subagents written', count((t) => t.agentsDir)),
    of('Slash commands written', count((t) => t.commandsDir)),
    of('MCP servers written', count((t) => t.mcpConfigFile)),
    '',
    '| Client | Category | Home | Rules | Hooks | Skills | Agents | Commands | MCP |',
    '|---|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
    '`npm run status` reports, per client and per component, whether what is on disk still matches the captured harness. `npm run explain` lists everything a client could not take, and why.',
    '',
    '## Adding a client',
    '',
    'Add an entry to `core/templates/targets.json`. Required: `id`, `name`, `category`, `rulesFile`, `preamble`. Optional: `home` (its presence on disk is what "installed" means), `adapter` (which `engine/harness/targets/<adapter>.cjs` renders it; omit for `generic`), `dialect`, `traitsFile`, `hooksConfigFile`, `skillsDir`, `sharedSkillDirs`, `agentsDir`, `commandsDir`, `mcpConfigFile`, `mcpFormat`, `permissionsFile`. Paths are `~`-relative and expanded at load; do not hardcode a client path anywhere else.',
    '',
    'Then run `npm run port:check`, `npm run docs:targets`, and commit the regenerated table. Field meanings in full: `engine/harness/README.md`.',
    '',
  ].join('\n');
}

function main() {
  const out = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(DOC_FILE) ? fs.readFileSync(DOC_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[targets-doc] docs/targets.md is stale. Run: npm run docs:targets');
      process.exit(1);
    }
    const { targets } = JSON.parse(fs.readFileSync(TARGETS_FILE, 'utf8'));
    console.log(`[targets-doc] docs/targets.md is current; clients=${targets.length}`);
    return;
  }
  fs.mkdirSync(path.dirname(DOC_FILE), { recursive: true });
  fs.writeFileSync(DOC_FILE, out, 'utf8');
  console.log(`[targets-doc] wrote ${path.relative(ROOT, DOC_FILE)}`);
}

if (require.main === module) main();

module.exports = { render };
